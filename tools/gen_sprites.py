#!/usr/bin/env python3
"""Convert pixel-art sheets into SpritesU plus-mask C arrays.

A source sheet is named ``<symbol>_<frame-width>x<frame-height>.png``. The
sheet may hold any number of frames in a row-major grid. Every frame is packed
as ``shades - 1`` bit planes; when any pixel has alpha it is packed as a
plus-mask sprite (a mask byte follows every data byte).

The compiler also emits a small C++ header with the dimensions and frame count
of every sheet. Keep both outputs deterministic: the packed bytes, the symbol
order, and the generated constants are part of the generated-file contract.
"""

import argparse
import re
from dataclasses import dataclass
from pathlib import Path

from PIL import Image

SHEET_RE = re.compile(r"^(?P<name>[A-Za-z_][A-Za-z0-9_]*)_(?P<width>[0-9]+)x(?P<height>[0-9]+)\.png$")


@dataclass(frozen=True)
class Sprite:
    name: str
    width: int
    height: int
    frames: int
    masked: bool
    data: bytes


def shade_bit(pixel, shades, plane):
    """Return the bit for one plane using the shared 4-shade convention."""
    step = (254 + shades) // shades
    return 1 if pixel[0] >= (plane + 1) * step else 0


def pack_sheet(path, shades):
    """Return a Sprite for one source sheet."""
    path = Path(path)
    match = SHEET_RE.match(path.name)
    if not match:
        raise ValueError(
            f"{path}: expected <symbol>_<width>x<height>.png, "
            "for example hauler_26x8.png"
        )
    if shades < 2 or shades > 4:
        raise ValueError("shades must be 2, 3, or 4")

    name = match.group("name")
    frame_width = int(match.group("width"))
    frame_height = int(match.group("height"))

    image = Image.open(path).convert("RGBA")
    if image.width % frame_width or image.height % frame_height:
        raise ValueError(
            f"{path}: image {image.width}x{image.height} is not a whole number "
            f"of {frame_width}x{frame_height} frames"
        )

    columns = image.width // frame_width
    rows = image.height // frame_height
    frames = columns * rows
    pixels = list(image.getdata())
    masked = any(pixel[3] < 255 for pixel in pixels)
    page_count = (frame_height + 7) // 8
    # SpritesU::drawPlusMaskFX(x, y, image, frame) reads the first two bytes as
    # width/height, then draws from image + 2.
    out = bytearray([frame_width, frame_height])

    for frame in range(frames):
        frame_x = (frame % columns) * frame_width
        frame_y = (frame // columns) * frame_height
        for plane in range(shades - 1):
            for page in range(page_count):
                for column in range(frame_width):
                    data = 0
                    mask = 0
                    for bit in range(8):
                        y = page * 8 + bit
                        if y >= frame_height:
                            break
                        pixel = pixels[(frame_y + y) * image.width + frame_x + column]
                        data |= shade_bit(pixel, shades, plane) << bit
                        mask |= (1 if pixel[3] >= 128 else 0) << bit
                    out.append(data)
                    if masked:
                        out.append(mask)

    return Sprite(name, frame_width, frame_height, frames, masked, bytes(out))


def collect_sprites(input_dir, shades):
    input_dir = Path(input_dir)
    sheets = sorted(
        path
        for path in input_dir.glob("*.png")
        if SHEET_RE.match(path.name)
    )
    if not sheets:
        raise ValueError(f"{input_dir}: no <symbol>_<width>x<height>.png sheets found")

    sprites = []
    seen = set()
    for path in sheets:
        sprite = pack_sheet(path, shades)
        if sprite.name in seen:
            raise ValueError(f"duplicate generated symbol: {sprite.name}")
        seen.add(sprite.name)
        sprites.append(sprite)
    return sprites


def render_arrays(sprites):
    blocks = []
    for sprite in sprites:
        lines = [
            "// Generated by tools/gen_sprites.py. Do not edit.",
            f"uint8_t {sprite.name}[] =",
            "{",
        ]
        for offset in range(0, len(sprite.data), 16):
            chunk = sprite.data[offset:offset + 16]
            lines.append("    " + " ".join(f"{value:3d}," for value in chunk))
        lines.append("};")
        lines.append("")
        blocks.append("\n".join(lines))
    return "\n".join(blocks)


def render_header(sprites):
    lines = [
        "// Generated by tools/gen_sprites.py. Do not edit.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
    ]
    for sprite in sprites:
        stem = sprite.name.upper()
        lines.extend(
            [
                f"constexpr uint8_t {stem}_WIDTH  = {sprite.width};",
                f"constexpr uint8_t {stem}_HEIGHT = {sprite.height};",
                f"constexpr uint8_t {stem}_FRAMES = {sprite.frames};",
                f"constexpr bool    {stem}_MASKED = {'true' if sprite.masked else 'false'};",
                "",
            ]
        )
    return "\n".join(lines)


def write_arrays(input_dir, output, shades, header=None):
    sprites = collect_sprites(input_dir, shades)
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render_arrays(sprites), encoding="utf-8")
    if header:
        header = Path(header)
        header.parent.mkdir(parents=True, exist_ok=True)
        header.write_text(render_header(sprites), encoding="utf-8")
    return sprites


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", default="images", help="directory of source PNG sheets")
    parser.add_argument("--output", default="fxdata/Sprites.txt", help="generated include")
    parser.add_argument("--header", default="src/generated/sprites.hpp", help="generated C++ constants")
    parser.add_argument("--shades", type=int, default=4, choices=(2, 3, 4))
    args = parser.parse_args(argv)
    write_arrays(args.input, args.output, args.shades, args.header)
    print(f"gen_sprites: wrote {args.output} and {args.header}")


if __name__ == "__main__":
    main()
