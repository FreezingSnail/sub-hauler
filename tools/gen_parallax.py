#!/usr/bin/env python3
"""Pack hand-authored regional backgrounds and pre-shifted FX scanlines."""
import json
from pathlib import Path
from PIL import Image
from parallax_art import AREAS, WIDTH, HEIGHT, plates

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "levels/exploration.json"
OUTPUT = ROOT / "src/generated/parallax.hpp"
PLANE = ROOT / "fxdata/tables/parallax.bin"
ART = ROOT / "images/parallax"
ROW_STRIDE = WIDTH + 128
BLOCK_WIDTH = 8
BLOCKS_PER_ROW = ROW_STRIDE // BLOCK_WIDTH
PHASE_BYTES = ROW_STRIDE * (HEIGHT // 8)
AREA_BYTES = PHASE_BYTES * 8


def pack(image):
    if image.size != (WIDTH, HEIGHT) or image.mode != "1":
        raise ValueError("regional backdrop must be a native 256x128 one-bit drawing")
    return bytes(sum(1 << bit if image.getpixel((x, y + bit)) else 0 for bit in range(8))
                 for y in range(0, HEIGHT, 8) for x in range(WIDTH))


def dotted(image):
    """Anchor the alternating screen to the artwork, so it scrolls with it."""
    result = image.copy()
    pixels = result.load()
    for y in range(HEIGHT):
        for x in range(WIDTH):
            if (x + y) & 1:
                pixels[x, y] = 0
    return result


def regions(source):
    rooms = source["rooms"]
    width, height = source["dimensions"]
    return bytes(AREAS.index(min(rooms, key=lambda room:
                 (x - room["position"][0]) ** 2 + (y - room["position"][1]) ** 2)["region"])
                 for y in range(height) for x in range(width))


def shifted(native):
    result = bytearray()
    for shift in range(8):
        for page in range(HEIGHT // 8):
            for x in range(ROW_STRIDE):
                column = x % WIDTH
                lower = native[page * WIDTH + column]
                upper = native[((page + 1) % (HEIGHT // 8)) * WIDTH + column]
                result.append(((lower >> shift) | (upper << (8 - shift))) & 255)
    return bytes(result)


def crc(data):
    value = 0xFFFF
    for byte in data:
        value ^= byte
        for _ in range(8):
            value = (value >> 1) ^ (0xA001 if value & 1 else 0)
    return value


def encode_row(row):
    """An occupancy byte followed by the nonzero native columns, in order."""
    if len(row) != BLOCK_WIDTH:
        raise ValueError("background block must contain exactly eight columns")
    mask = sum(1 << i for i, value in enumerate(row) if value)
    return bytes([mask]) + bytes(value for value in row if value)


def main():
    source = json.loads(SOURCE.read_text())
    drawings = tuple(dotted(image) for image in plates())
    natives = [pack(image) for image in drawings]
    ART.mkdir(parents=True, exist_ok=True)
    for name, image in zip(AREAS, drawings):
        image.save(ART / (name + ".png"))
    ownership = regions(source)
    rows = []
    for native in natives:
        data = shifted(native)
        rows.extend(encode_row(data[i:i + BLOCK_WIDTH]) for i in range(0, len(data), BLOCK_WIDTH))
    offset = len(ownership) + len(rows) * 3
    offsets = bytearray()
    for row in rows:
        offsets.extend(offset.to_bytes(3, "little"))
        offset += len(row)
    PLANE.write_bytes(ownership + offsets + b"".join(rows))
    lines = ["// Generated by make gen from tools/parallax_art.py and levels/exploration.json.",
             "#pragma once", "#include <stdint.h>", "#if defined(__AVR__)",
             "#include <avr/pgmspace.h>", "#define PARALLAX_PROGMEM PROGMEM", "#else",
             "#define PARALLAX_PROGMEM", "#endif", "namespace parallax_data {",
             "constexpr uint8_t kAreaCount = 4;", "constexpr uint16_t kWidth = 256;",
             "constexpr uint8_t kHeight = 128;", "constexpr uint16_t kRowStride = 384;",
             "constexpr uint16_t kPhaseBytes = 6144;", "constexpr uint16_t kAreaBytes = 49152;",
             "constexpr uint16_t kMapBytes = 51200;", "constexpr uint8_t kRowsPerPhase = 16;",
             "constexpr uint8_t kRowsPerArea = 128;", "constexpr uint8_t kBlockWidth = 8;",
             "constexpr uint8_t kBlocksPerRow = 48;"]
    lines.append("constexpr uint32_t kBytes = {};".format(PLANE.stat().st_size))
    for i, name in enumerate(AREAS):
        lines.append("constexpr uint8_t kArea{} = {};".format(name.title(), i))
    checks = []
    for name, native in zip(AREAS, natives):
        room = next(r for r in source["rooms"] if r["region"] == name)
        x, y = room["position"][0] * 8 - 64, room["position"][1] * 8 - 32
        crop = bytes(sum(1 << b if native[(((y // 2 + sy + b) % HEIGHT) // 8) * WIDTH +
                         ((x // 2 + sx) % WIDTH)] & (1 << ((y // 2 + sy + b) % 8)) else 0
                         for b in range(8)) for sy in range(0, 64, 8) for sx in range(128))
        checks.append((x, y, crc(crop)))
    for column, name in enumerate(("X", "Y", "Crc")):
        lines.append("const uint16_t kCheck{}[kAreaCount] PARALLAX_PROGMEM = {{{}}};".format(
            name, ", ".join(str(check[column]) for check in checks)))
    lines.extend(["#if !defined(__AVR__)", "const uint8_t kNative[kAreaCount][4096] = {"])
    for native in natives:
        lines.append("{")
        lines.extend("    " + ", ".join("0x{:02X}".format(v) for v in native[i:i + 16]) + ","
                     for i in range(0, len(native), 16))
        lines.append("},")
    lines.extend(["};", "#endif", "}", "#undef PARALLAX_PROGMEM", ""])
    OUTPUT.write_text("\n".join(lines))
    print("parallax: 4 hand-drawn 256x128 areas; {} B FX map + shifted artwork".format(PLANE.stat().st_size))


if __name__ == "__main__":
    main()
