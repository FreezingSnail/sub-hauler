def escape(text: str) -> str:
    return html.escape(text, quote=False)


def slug(text: str) -> str:
    value = re.sub(r"`", "", text).lower()
    value = re.sub(r"[^a-z0-9]+", "-", value).strip("-")
    return value or "section"


def rewrite_target(target: str, source_dir: Path) -> str:
    """Point repository links at GitHub; leave anchors and absolute URLs alone."""
    if target.startswith(("http://", "https://", "mailto:", "#")):
        return target
    path, _, fragment = target.partition("#")
    if not path:
        return target
    try:
        resolved = (source_dir / path).resolve()
        relative = resolved.relative_to(ROOT).as_posix()
    except (ValueError, OSError):
        return target
    base = BLOB if resolved.suffix else TREE
    return base + relative + (("#" + fragment) if fragment else "")


def inline(text: str, source_dir: Path) -> str:
    placeholders: list[str] = []

    def keep_code(match):
        placeholders.append("<code>" + escape(match.group(1)) + "</code>")
        return "\x00{}\x00".format(len(placeholders) - 1)

    text = INLINE_CODE.sub(keep_code, text)
    text = escape(text)

    def keep_link(match):
        label = BOLD.sub(r"<strong>\1</strong>", match.group(1))
        target = rewrite_target(html.unescape(match.group(2)), source_dir)
        return '<a href="{}">{}</a>'.format(html.escape(target, quote=True), label)

    text = LINK.sub(keep_link, text)
    text = BOLD.sub(r"<strong>\1</strong>", text)
    for index, value in enumerate(placeholders):
        text = text.replace("\x00{}\x00".format(index), value)
    return text


def render_table(lines: list[str], source_dir: Path, start: int):
    header = [cell.strip() for cell in lines[start].strip().strip("|").split("|")]
    alignment = []
    for cell in lines[start + 1].strip().strip("|").split("|"):
        cell = cell.strip()
        if cell.startswith(":") and cell.endswith(":"):
            alignment.append("center")
        elif cell.endswith(":"):
            alignment.append("right")
        else:
            alignment.append("")
    index = start + 2
    rows = []
    while index < len(lines) and "|" in lines[index] and lines[index].strip():
        rows.append([cell.strip() for cell in lines[index].strip().strip("|").split("|")])
        index += 1

    def cells(tag, values):
        parts = []
        for position, value in enumerate(values):
            css = alignment[position] if position < len(alignment) else ""
            css_class = ' class="align-{}"'.format(css) if css else ""
            parts.append("<{}{}>{}</{}>".format(tag, css_class, inline(value, source_dir), tag))
        return "".join(parts)

    out = ['<div class="table-wrap"><table>', "<thead><tr>" + cells("th", header) + "</tr></thead>", "<tbody>"]
    for row in rows:
        out.append("<tr>" + cells("td", row) + "</tr>")
    out.append("</tbody></table></div>")
    return out, index


def render(markdown: str, source_dir: Path | None = None) -> str:
    source_dir = source_dir or SOURCE.parent
    lines = markdown.splitlines()
    body: list[str] = []
    headings: list[tuple[int, str, str]] = []
    paragraph: list[str] = []
    list_kind = None
    list_items: list[str] = []
    index = 0

    def flush_paragraph():
        if paragraph:
            body.append("<p>" + inline(" ".join(paragraph), source_dir) + "</p>")
            paragraph.clear()

    def flush_list():
        nonlocal list_kind
        if list_kind:
            tag = "ul" if list_kind == "ul" else "ol"
            body.append("<{}>".format(tag))
            for item in list_items:
                body.append("<li>" + inline(item, source_dir) + "</li>")
            body.append("</{}>".format(tag))
            list_items.clear()
            list_kind = None

    def flush_blocks():
        flush_paragraph()
        flush_list()

    while index < len(lines):
        line = lines[index]
        stripped = line.strip()

        if stripped.startswith("```"):
            flush_blocks()
            index += 1
            code = []
            while index < len(lines) and not lines[index].strip().startswith("```"):
                code.append(lines[index])
                index += 1
            body.append("<pre><code>" + escape("\n".join(code)) + "</code></pre>")
            index += 1
            continue

        if not stripped:
            flush_blocks()
            index += 1
            continue

        heading = HEADING.match(line)
        if heading:
            flush_blocks()
            level = len(heading.group(1))
            text = heading.group(2)
            headings.append((level, text, slug(text)))
            if level > 1:
                body.append('<h{0} id="{1}">{2}</h{0}>'.format(level, slug(text), inline(text, source_dir)))
            index += 1
            continue

        if (
            "|" in line
            and index + 1 < len(lines)
            and TABLE_DELIMITER.match(lines[index + 1])
            and "-" in lines[index + 1]
        ):
            flush_blocks()
            table, index = render_table(lines, source_dir, index)
            body.extend(table)
            continue

        unordered = UNORDERED.match(line)
        ordered = ORDERED.match(line)
        if unordered or ordered:
            flush_paragraph()
            kind = "ul" if unordered else "ol"
            if list_kind and list_kind != kind:
                flush_list()
            list_kind = kind
            item = (unordered or ordered).group(1 if unordered else 2)
            list_items.append(item)
            index += 1
            continue

        if list_items and line.startswith((" ", "\t")):
            list_items[-1] += " " + stripped
            index += 1
            continue

        flush_list()
        paragraph.append(stripped)
        index += 1

    flush_blocks()

    section_anchors = [(text, anchor) for level, text, anchor in headings if level == 2]
    nav = "\n".join(
        '    <a href="#{}">{}</a>'.format(anchor, escape(text)) for text, anchor in section_anchors
    )
    variables = {
        "@@NAV@@": nav,
        "@@REPOSITORY@@": REPOSITORY,
        "@@SOURCE_URL@@": BLOB + "docs/making-of.md",
    }
    page = PAGE_HEAD + "\n" + "\n".join(body) + "\n" + PAGE_TAIL
    for token, value in variables.items():
        page = page.replace(token, value)
    return page


def generate() -> str:
    return render(SOURCE.read_text(encoding="utf-8"))


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if docs/making-of.html is stale")
    args = parser.parse_args(argv)

    page = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != page:
            print("making-of: docs/making-of.html is stale; run `make docs-page`", file=sys.stderr)
            return 1
        print("making-of: docs/making-of.html matches docs/making-of.md")
        return 0

    OUTPUT.write_text(page, encoding="utf-8")
    print("making-of: wrote docs/making-of.html from docs/making-of.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
