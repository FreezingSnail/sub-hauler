#!/usr/bin/env python3
"""Export original scores with the sibling ATMlib2FX authoring tool."""

import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
RING = 64


def main():
    library = Path(os.environ.get("ATMLIB2FX_ROOT", ROOT.parent / "ATMlib2FX"))
    cli = library / "tools/atm-music"
    if not cli.is_file():
        raise SystemExit("gen-music: set ATMLIB2FX_ROOT to an ATMlib2FX checkout")
    catalog = json.loads((ROOT / "music/catalog.json").read_text())
    destination = ROOT / "fxdata/music"
    destination.mkdir(parents=True, exist_ok=True)
    records = []
    lengths = []
    for entry in catalog["entries"]:
        song_id = entry["id"]
        out = f"build/music/{song_id}"
        result = subprocess.run(
            [sys.executable, str(cli), "build", entry["source"], "--backend", "fx",
             "--ring", str(RING), "--streaming-loops", "--out", out, "--json"],
            cwd=ROOT, capture_output=True, text=True, check=False,
        )
        if result.returncode:
            raise SystemExit(result.stderr + result.stdout)
        payload = json.loads(result.stdout)
        report = payload["report"]
        stream = (ROOT / out / "stream.bin").read_bytes()
        if payload["diagnostics"] or not report["loop_exported"] or stream[0] != 0xC1:
            raise SystemExit(f"gen-music: {song_id} must export a loop without warnings")
        (destination / f"{song_id}.bin").write_bytes(stream)
        lengths.append((song_id, len(stream)))
        records.append({
            **entry,
            "bytes": len(stream),
            "sha256": hashlib.sha256(stream).hexdigest(),
            "source_sha256": report["source"]["sha256"],
            "event_digest": report["event_digest"],
            "clock": report["clock"],
            "total_ticks": report["total_ticks"],
            "stream": report["stream"],
        })
        print(f"music: {entry['name']}: {len(stream)} B, looping, no warnings")
    (destination / "manifest.json").write_text(json.dumps({
        "format": "atm_fx_compact_v1", "ring": RING,
        "streaming_loops": True, "songs": records,
    }, indent=2) + "\n")
    header = ["// Generated by make gen. Do not edit.", "#pragma once",
              "#include <stdint.h>", "namespace music_data {",
              f"constexpr uint8_t RING_BYTES = {RING};"]
    header += [f"constexpr uint32_t {song_id}_bytes = {length};" for song_id, length in lengths]
    header += ["} // namespace music_data", ""]
    (ROOT / "src/generated/music.hpp").write_text("\n".join(header))


if __name__ == "__main__":
    main()
