#!/usr/bin/env python3
"""Build the external 6x8 text font image from a compact ASCII glyph table.

The installed Arduboy2 5x7 font draws a 6x8 cell (five glyph columns plus one
spacing column). This tool copies the needed IBM PC code page 437 glyphs into
that same cell and writes a 256-frame strip, so ``FX::drawChar(code)`` can use
the character value directly as a frame index. Unused codes stay blank.

The output is a normal opaque 1-bit source image for ``fxdata-build.py``; it is
not a packed sprite. Keep the bytes deterministic: the glyph table, the frame
order, and the generated PNG are part of the FX layout contract.
"""

import argparse
from pathlib import Path

from PIL import Image

FRAME_WIDTH = 6
FRAME_HEIGHT = 8
FRAME_COUNT = 256

# ASCII space, '-', '/', ':', '0'..'9', and 'A'..'Z' from the Arduboy2 5x7
# font (IBM PC code page 437). Each tuple is five column bytes, bit 0 = top.
GLYPHS = {
    0x20: (0x00, 0x00, 0x00, 0x00, 0x00),
    0x2D: (0x08, 0x08, 0x08, 0x08, 0x08),
    0x2F: (0x20, 0x10, 0x08, 0x04, 0x02),
    0x30: (0x3E, 0x51, 0x49, 0x45, 0x3E),
    0x31: (0x00, 0x42, 0x7F, 0x40, 0x00),
    0x32: (0x72, 0x49, 0x49, 0x49, 0x46),
    0x33: (0x21, 0x41, 0x49, 0x4D, 0x33),
    0x34: (0x18, 0x14, 0x12, 0x7F, 0x10),
    0x35: (0x27, 0x45, 0x45, 0x45, 0x39),
    0x36: (0x3C, 0x4A, 0x49, 0x49, 0x31),
    0x37: (0x41, 0x21, 0x11, 0x09, 0x07),
    0x38: (0x36, 0x49, 0x49, 0x49, 0x36),
    0x39: (0x46, 0x49, 0x49, 0x29, 0x1E),
    0x3A: (0x00, 0x00, 0x14, 0x00, 0x00),
    0x41: (0x7C, 0x12, 0x11, 0x12, 0x7C),
    0x42: (0x7F, 0x49, 0x49, 0x49, 0x36),
    0x43: (0x3E, 0x41, 0x41, 0x41, 0x22),
    0x44: (0x7F, 0x41, 0x41, 0x41, 0x3E),
    0x45: (0x7F, 0x49, 0x49, 0x49, 0x41),
    0x46: (0x7F, 0x09, 0x09, 0x09, 0x01),
    0x47: (0x3E, 0x41, 0x41, 0x51, 0x73),
    0x48: (0x7F, 0x08, 0x08, 0x08, 0x7F),
    0x49: (0x00, 0x41, 0x7F, 0x41, 0x00),
    0x4A: (0x20, 0x40, 0x41, 0x3F, 0x01),
    0x4B: (0x7F, 0x08, 0x14, 0x22, 0x41),
    0x4C: (0x7F, 0x40, 0x40, 0x40, 0x40),
    0x4D: (0x7F, 0x02, 0x1C, 0x02, 0x7F),
    0x4E: (0x7F, 0x04, 0x08, 0x10, 0x7F),
    0x4F: (0x3E, 0x41, 0x41, 0x41, 0x3E),
    0x50: (0x7F, 0x09, 0x09, 0x09, 0x06),
    0x51: (0x3E, 0x41, 0x51, 0x21, 0x5E),
    0x52: (0x7F, 0x09, 0x19, 0x29, 0x46),
    0x53: (0x26, 0x49, 0x49, 0x49, 0x32),
    0x54: (0x03, 0x01, 0x7F, 0x01, 0x03),
    0x55: (0x3F, 0x40, 0x40, 0x40, 0x3F),
    0x56: (0x1F, 0x20, 0x40, 0x20, 0x1F),
    0x57: (0x3F, 0x40, 0x38, 0x40, 0x3F),
    0x58: (0x63, 0x14, 0x08, 0x14, 0x63),
    0x59: (0x03, 0x04, 0x78, 0x04, 0x03),
    0x5A: (0x61, 0x59, 0x49, 0x4D, 0x43),
}


def build_image():
    """Return the opaque 256-frame RGBA strip."""
    image = Image.new("RGBA", (FRAME_WIDTH * FRAME_COUNT, FRAME_HEIGHT), (0, 0, 0, 255))
    pixels = image.load()
    for code, columns in GLYPHS.items():
        base = code * FRAME_WIDTH
        for column, bits in enumerate(columns):
            for row in range(FRAME_HEIGHT):
                if bits & (1 << row):
                    pixels[base + column, row] = (255, 255, 255, 255)
    return image


def write_font(output):
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    build_image().save(output)
    return output


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="fxdata/fonts/font_6x8.png")
    args = parser.parse_args(argv)
    print("gen_font: wrote {}".format(write_font(args.output)))


if __name__ == "__main__":
    main()
